import mongoose from 'mongoose';
import dotenv from 'dotenv';
import { fileURLToPath } from 'url';
import path from 'path';
const __dirname = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.resolve(__dirname, '../.env') });
const MONGO_URI = process.env.MONGODB_URI || process.env.MONGO_URI;
await mongoose.connect(MONGO_URI);
await import('../models/PatientsView.js');
const Patient = (await import('../models/Patient.js')).default;
const { listGuidesPendingBilling } = await import('../services/insuranceBatchGuideAdapter.js');
const p = await Patient.findOne({ fullName: { $regex: 'Nicolas Lucca', $options: 'i' } }).lean();
const result = await listGuidesPendingBilling({ patientId: p._id.toString() });
const g = result.guides[0];
console.log('guide keys:', Object.keys(g));
console.log('sessions present?', Array.isArray(g.sessions), g.sessions?.length);
const sample = JSON.stringify({ guideId: g.guideId, number: g.number, sessions: g.sessions }, null, 2);
console.log('JSON sample:', sample.slice(0, 900));
await mongoose.disconnect();
